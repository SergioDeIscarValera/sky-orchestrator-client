#!/usr/bin/env bash
#
# Regenerate auth-functions.sql: the auth schema's helper functions as GoTrue's
# migrations leave them in production, for the database tests (NFR-TEST-02).
#
# The Postgres image ships an older auth.uid() that reads only the legacy
# request.jwt.claim.sub setting; GoTrue replaces it on its first start. A
# throwaway Postgres and a throwaway GoTrue, the versions Virtual Origen runs, on
# a private network with no published port.
#
# Usage: database/fixtures/generate-auth-functions.sh > database/fixtures/auth-functions.sql

set -euo pipefail

POSTGRES_IMAGE=supabase/postgres:17.6.1.136
GOTRUE_IMAGE=supabase/gotrue:v2.189.0
run_id="soc-fixture-$$"
password="$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')"
jwt_secret="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"

cleanup() {
  docker rm -f "$run_id-auth" "$run_id-db" >/dev/null 2>&1 || true
  docker network rm "$run_id" >/dev/null 2>&1 || true
}
trap cleanup EXIT

docker network create "$run_id" >/dev/null
docker run -d --name "$run_id-db" --network "$run_id" --network-alias db \
  -e POSTGRES_PASSWORD="$password" -e JWT_SECRET="$jwt_secret" -e JWT_EXP=3600 \
  "$POSTGRES_IMAGE" >/dev/null

psql_db() { docker exec "$run_id-db" psql -h localhost -U supabase_admin -d postgres -Atqc "$1"; }

for _ in $(seq 1 120); do
  psql_db "select 1" >/dev/null 2>&1 && break
  sleep 1
done
sleep 3
psql_db "alter user supabase_auth_admin with password '$password'"

docker run -d --name "$run_id-auth" --network "$run_id" \
  -e GOTRUE_API_HOST=0.0.0.0 -e GOTRUE_API_PORT=9999 -e API_EXTERNAL_URL=http://localhost:8000 \
  -e GOTRUE_DB_DRIVER=postgres \
  -e GOTRUE_DB_DATABASE_URL="postgres://supabase_auth_admin:$password@db:5432/postgres" \
  -e GOTRUE_SITE_URL=http://localhost:3000 -e GOTRUE_JWT_SECRET="$jwt_secret" -e GOTRUE_JWT_EXP=3600 \
  -e GOTRUE_JWT_AUD=authenticated -e GOTRUE_JWT_DEFAULT_GROUP_NAME=authenticated \
  -e GOTRUE_JWT_ADMIN_ROLES=service_role -e GOTRUE_DISABLE_SIGNUP=true \
  "$GOTRUE_IMAGE" >/dev/null

for _ in $(seq 1 180); do
  [ "$(psql_db "select pg_get_functiondef('auth.uid'::regproc) like '%request.jwt.claims%'" 2>/dev/null)" = t ] && break
  sleep 1
done
[ "$(psql_db "select pg_get_functiondef('auth.uid'::regproc) like '%request.jwt.claims%'")" = t ] \
  || { echo "GoTrue never replaced auth.uid()" >&2; docker logs "$run_id-auth" | tail -20 >&2; exit 1; }

postgres_digest="$(docker image inspect --format '{{index .RepoDigests 0}}' "$POSTGRES_IMAGE")"
gotrue_digest="$(docker image inspect --format '{{index .RepoDigests 0}}' "$GOTRUE_IMAGE")"
output="$(
  {
    printf -- '-- Generated by database/fixtures/generate-auth-functions.sh. Do not edit by hand.\n'
    printf -- '-- The auth helper functions as %s leaves them on %s.\n\n' "$gotrue_digest" "$postgres_digest"
    psql_db "
      select pg_get_functiondef(p.oid) || ';'
      from pg_proc p
      where p.pronamespace = 'auth'::regnamespace and p.proname in ('uid', 'role', 'email', 'jwt')
      order by p.proname;"
  } | sed 's/[[:space:]]*$//' | cat -s
)"
printf '%s\n' "$output"
