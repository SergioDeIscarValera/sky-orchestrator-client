#!/usr/bin/env bash
#
# Regenerate realtime-schema.sql: the `realtime` schema exactly as Realtime creates
# it in a tenant database, for the database tests (NFR-TEST-02).
#
# A throwaway Postgres and a throwaway Realtime, the image versions Virtual Origen
# runs in production, on a private network with no published port. Realtime
# migrates its tenant schema on start; the schema is dumped without the daily
# partitions of realtime.messages, which tests create for their own time window.
#
# Usage: database/fixtures/generate-realtime-schema.sh > database/fixtures/realtime-schema.sql

set -euo pipefail

POSTGRES_IMAGE=supabase/postgres:17.6.1.136
REALTIME_IMAGE=supabase/realtime:v2.102.3
run_id="soc-fixture-$$"
password="$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')"
jwt_secret="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"

cleanup() {
  docker rm -f "$run_id-realtime" "$run_id-db" >/dev/null 2>&1 || true
  docker network rm "$run_id" >/dev/null 2>&1 || true
}
trap cleanup EXIT

docker network create "$run_id" >/dev/null
docker run -d --name "$run_id-db" --network "$run_id" --network-alias db \
  -e POSTGRES_PASSWORD="$password" -e JWT_SECRET="$jwt_secret" -e JWT_EXP=3600 \
  "$POSTGRES_IMAGE" >/dev/null

psql_db() { docker exec -e PGPASSWORD="$password" "$run_id-db" psql -h localhost -U supabase_admin -d postgres -Atqc "$1"; }

for _ in $(seq 1 120); do
  psql_db "select 1" >/dev/null 2>&1 && break
  sleep 1
done
psql_db "create schema if not exists _realtime; alter schema _realtime owner to supabase_admin;"

docker run -d --name "$run_id-realtime" --network "$run_id" \
  -e PORT=4000 -e DB_HOST=db -e DB_PORT=5432 -e DB_USER=supabase_admin \
  -e DB_PASSWORD="$password" -e DB_NAME=postgres \
  -e DB_AFTER_CONNECT_QUERY='SET search_path TO _realtime' -e DB_ENC_KEY=supabaserealtime \
  -e API_JWT_SECRET="$jwt_secret" -e METRICS_JWT_SECRET="$jwt_secret" -e API_JWT_JWKS=null \
  -e SECRET_KEY_BASE="$(head -c 48 /dev/urandom | od -An -tx1 | tr -d ' \n')" \
  -e ERL_AFLAGS='-proto_dist inet_tcp' -e DNS_NODES="''" -e RLIMIT_NOFILE=10000 \
  -e APP_NAME=realtime -e SEED_SELF_HOST=true -e RUN_JANITOR=true \
  "$REALTIME_IMAGE" >/dev/null

for _ in $(seq 1 180); do
  [ "$(psql_db "select to_regclass('realtime.messages') is not null and to_regprocedure('realtime.send(jsonb,text,text,boolean)') is not null" 2>/dev/null)" = t ] && break
  sleep 1
done
[ "$(psql_db "select to_regclass('realtime.messages') is not null")" = t ] || { echo "realtime never created its schema" >&2; docker logs "$run_id-realtime" | tail -20 >&2; exit 1; }
sleep 3

postgres_digest="$(docker image inspect --format '{{index .RepoDigests 0}}' "$POSTGRES_IMAGE")"
realtime_digest="$(docker image inspect --format '{{index .RepoDigests 0}}' "$REALTIME_IMAGE")"
output="$(
  {
    printf -- '-- Generated by database/fixtures/generate-realtime-schema.sh. Do not edit by hand.\n'
    printf -- '-- The realtime schema as %s creates it in a tenant database on %s,\n' "$realtime_digest" "$postgres_digest"
    printf -- '-- without the daily partitions of realtime.messages, preceded by the roles\n'
    printf -- '-- Realtime creates and their memberships, which pg_dump does not carry.\n\n'
    psql_db "
      select format(
        'DO \$\$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = %L) THEN CREATE ROLE %I %s %s %s %s %s; END IF; END \$\$;',
        r.rolname, r.rolname,
        case when r.rolcanlogin then 'LOGIN' else 'NOLOGIN' end,
        case when r.rolinherit then 'INHERIT' else 'NOINHERIT' end,
        case when r.rolcreaterole then 'CREATEROLE' else 'NOCREATEROLE' end,
        case when r.rolreplication then 'REPLICATION' else 'NOREPLICATION' end,
        case when r.rolbypassrls then 'BYPASSRLS' else 'NOBYPASSRLS' end)
      from pg_roles r
      where r.rolname in (select distinct pg_get_userbyid(c.relowner) from pg_class c where c.relnamespace = 'realtime'::regnamespace
                          union select distinct pg_get_userbyid(p.proowner) from pg_proc p where p.pronamespace = 'realtime'::regnamespace)
        and not r.rolsuper
      order by r.rolname;
      select format('GRANT %I TO %I;', pg_get_userbyid(m.roleid), pg_get_userbyid(m.member))
      from pg_auth_members m
      where pg_get_userbyid(m.roleid) = 'supabase_realtime_admin' or pg_get_userbyid(m.member) = 'supabase_realtime_admin'
      order by 1;"
    printf '\n'
    docker exec -e PGPASSWORD="$password" "$run_id-db" pg_dump -h localhost -U supabase_admin -d postgres \
      --schema-only --schema=realtime --exclude-table='realtime.messages_*' --no-comments \
      | grep -v '^\\restrict\|^\\unrestrict\|^SELECT pg_catalog.set_config(.search_path.' \
      | sed '/^--/d; s/^CREATE SCHEMA realtime;/CREATE SCHEMA IF NOT EXISTS realtime;/' | cat -s
  } | sed 's/[[:space:]]*$//' | cat -s
)"
printf '%s\n' "$output"
