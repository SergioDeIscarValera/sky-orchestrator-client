"""Writes contracts/geometry/projection.json from PROJ, the test oracle (ADR-0009).

    uv run python libs/soc-geo/tests/oracle.py > contracts/geometry/projection.json

Each point lies a geodesic distance and bearing from its origin, so the vectors
cover the site's extent (2.5 km) in every direction, at the farm and at the
places a closed form goes wrong: the equator, high latitude, the southern
hemisphere and across the antimeridian. pyproj never runs in a service.
"""

from __future__ import annotations

import json
import sys
from typing import Any

import pyproj

TOLERANCE_M = 1e-6
ORIGINS = {
    "farm": (41.6523, -4.7245),
    "equator": (0.0, 0.0),
    "arctic": (69.65, 18.96),
    "south": (-33.87, 151.21),
    "antimeridian": (0.5, 179.9995),
}
DISTANCES_M = (1.0, 100.0, 1000.0, 2500.0)
BEARINGS_DEG = (0.0, 45.0, 90.0, 180.0, 270.0, 333.0)


def topocentric(latitude: float, longitude: float) -> pyproj.Transformer:
    return pyproj.Transformer.from_pipeline(
        "+proj=pipeline +step +proj=cart +ellps=WGS84 "
        f"+step +proj=topocentric +ellps=WGS84 +lat_0={latitude!r} +lon_0={longitude!r} +h_0=0"
    )


def case(name: str, origin: tuple[float, float], point: tuple[float, float]) -> dict[str, Any]:
    east, north, _ = topocentric(*origin).transform(point[1], point[0], 0.0)
    return {
        "name": name,
        "origin": {"latitude_deg": origin[0], "longitude_deg": origin[1]},
        "point": {"latitude_deg": point[0], "longitude_deg": point[1]},
        "east_m": round(east, 9),
        "north_m": round(north, 9),
    }


def vectors() -> dict[str, Any]:
    geodesic = pyproj.Geod(ellps="WGS84")
    cases = []
    for place, origin in ORIGINS.items():
        cases.append(case(f"{place}: the origin itself", origin, origin))
        for distance in DISTANCES_M:
            for bearing in BEARINGS_DEG:
                longitude, latitude, _ = geodesic.fwd(origin[1], origin[0], bearing, distance)
                point = (round(latitude, 10), round((longitude + 180) % 360 - 180, 10))
                cases.append(case(f"{place}: {distance:g} m at {bearing:g}°", origin, point))
    return {
        "description": (
            "The east-north tangent plane at an origin on the WGS84 ellipsoid (ADR-0009, "
            "ADR-0014): where a point lies, in metres, both at the ellipsoid's surface. "
            "Generated by libs/soc-geo/tests/oracle.py from PROJ; every implementation "
            "of the projection passes every case within tolerance_m."
        ),
        "oracle": f"PROJ {pyproj.proj_version_str} through pyproj {pyproj.__version__}",
        "tolerance_m": TOLERANCE_M,
        "cases": cases,
    }


def main() -> int:
    json.dump(vectors(), sys.stdout, indent=2, ensure_ascii=False)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
